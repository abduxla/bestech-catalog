#!/usr/bin/env node
// =====================================================================
// Bundle the numbered migrations into one bootstrap file.
//
//   node scripts/bundle-migrations.mjs    -> supabase/bootstrap.sql
//
// Why this exists: applying migrations properly needs `supabase db
// push`, which needs the CLI logged in and the database password. On a
// brand new project that is a credential round trip before anyone can
// see anything work. This produces a single file that can be pasted
// into the dashboard SQL editor once, to get an empty project to the
// same state.
//
// It is explicitly a BOOTSTRAP, not a way of working. The project's
// rule is that schema changes are numbered migration files applied with
// the CLI, because the previous project ended up with production
// columns that existed in no SQL file and a repo that could not rebuild
// its own database. This file is generated FROM those migrations and is
// never edited by hand, so that rule still holds.
//
// Two things make it safe:
//   * the whole thing runs in one transaction, so a failure applies
//     nothing rather than leaving a half-built schema;
//   * it records every bundled migration in
//     supabase_migrations.schema_migrations, so the first real
//     `supabase db push` does not try to re-run them and die on
//     "relation already exists".
// =====================================================================

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'supabase', 'migrations');
const OUT = join(ROOT, 'supabase', 'bootstrap.sql');

const files = readdirSync(DIR).filter((f) => /^\d+_.*\.sql$/.test(f)).sort();
if (!files.length) {
  console.error('\n  No migrations found in supabase/migrations.\n');
  process.exit(1);
}

const rule = '-- ' + '='.repeat(69);

const parts = [
  rule,
  '-- BESTECH CATALOGUE — COMPLETE SCHEMA BOOTSTRAP',
  '--',
  '-- GENERATED by scripts/bundle-migrations.mjs. Do not edit this file:',
  '-- edit the migration it came from and regenerate, or the repo stops',
  '-- being able to rebuild the database — the exact failure this',
  '-- project is built to avoid.',
  '--',
  '-- Run this ONCE, in the Supabase dashboard SQL editor, to bootstrap',
  '-- an empty project. Every change after this is a NEW numbered',
  '-- migration applied with `supabase db push`.',
  '--',
  '-- Wrapped in a transaction: if any statement fails, nothing is',
  '-- applied and the database is left exactly as it was. There is no',
  '-- half-migrated state to unpick.',
  '--',
  `-- Bundled: ${files.join(', ')}`,
  rule,
  '',
  'begin;',
  '',
];

for (const file of files) {
  parts.push('', rule, `-- ${file}`, rule, '', readFileSync(join(DIR, file), 'utf8').trimEnd(), '');
}

// Tell the CLI these are already applied.
const rows = files.map((f) => {
  const base = basename(f, '.sql');
  const i = base.indexOf('_');
  return `  ('${base.slice(0, i)}', '${base.slice(i + 1)}')`;
});

parts.push(
  '',
  rule,
  '-- Record what has been applied, so a later `supabase db push` does',
  '-- not try to run these again and fail on "relation already exists".',
  rule,
  'create schema if not exists supabase_migrations;',
  'create table if not exists supabase_migrations.schema_migrations (',
  '  version    text primary key,',
  '  statements text[],',
  '  name       text',
  ');',
  'insert into supabase_migrations.schema_migrations (version, name) values',
  rows.join(',\n'),
  'on conflict (version) do nothing;',
  '',
  'commit;',
  '',
);

const sql = parts.join('\n');
writeFileSync(OUT, sql, 'utf8');

console.log(`\n  Bundled ${files.length} migrations -> supabase/bootstrap.sql`);
console.log(`  ${sql.split('\n').length} lines, ${(sql.length / 1024).toFixed(1)}KB\n`);
for (const f of files) console.log(`    ${f}`);
console.log('\n  Paste it into the Supabase SQL editor and run it once.\n');
